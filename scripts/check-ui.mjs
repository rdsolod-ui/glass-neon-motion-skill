import {readFile,stat} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {uiGroups,uiCount,uiAtlasSection} from './ui-atlas-section.mjs';
const checks=[];const check=(name,ok)=>{assert.ok(ok,name);checks.push(name);};
const specimens=uiGroups.flatMap(g=>g.specimens);
check('UI groups cover exactly 01–24',uiGroups.map(g=>g.number).join(',')===Array.from({length:24},(_,i)=>i+1).join(','));
check('UI group slugs unique',new Set(uiGroups.map(g=>g.id)).size===24);
check('Every group has multiple substantive specimens',uiGroups.every(g=>g.specimens.length>=2));
check('UI specimen IDs unique',new Set(specimens.map(s=>s.id)).size===uiCount);
check('Every specimen has title, keywords, markup, motion and boundary',specimens.every(s=>s.title&&s.tags&&s.html&&s.motion&&s.note));
const board=await readFile('site/moodboard.html','utf8');
check('Published UI section equals generated source',board.includes(uiAtlasSection()));
const ids=[...board.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
check('Whole moodboard IDs unique',ids.length===new Set(ids).size);
const manifest=JSON.parse(await readFile('site/ui-manifest.json','utf8'));
check('Manifest counts and IDs match source',manifest.count===uiCount&&manifest.groups.flatMap(g=>g.specimens).map(s=>s.id).join('|')===specimens.map(s=>'ui-'+s.id).join('|'));
for(const file of ['site/ui-atlas.js','site/ui-atlas.css','site/ui-controls.js','site/ui-controls.css','site/ui-compositions.js','site/ui-compositions.css','site/ui-data.js','site/ui-data.css'])await stat(file);
check('All UI runtime assets exist',true);
check('No replacement glyphs in UI source',!uiAtlasSection().includes('\ufffd'));
check('Global search entry and per-example anchors exist',board.includes('id="ui-search"')&&specimens.every(s=>board.includes(`id="ui-${s.id}"`)));
console.log(JSON.stringify({uiChecks:checks.length,groups:uiGroups.length,examples:uiCount,checks},null,2));
